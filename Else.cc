RELEASE_TEST("math/else/reversible") = [](Context ct) {
    // StaticRNG.seed(12876);
    la::arma_rng::set_seed_random();

    repeat_test(ct, 1000, [&](Ignore) {
        auto const n = 10;
        Mat<real> L = la::randu(n, n);
        L = L + L.t();
        L = L - 1.05 * la::diagmat(la::sum(L, 0));
        Col<real> p0 = la::randu(n);
        p0 /= la::accu(p0);
        Mat<real> const R = la::diagmat(1/p0) * L;
        Col<real> const p = random_float() * p0;

        math::ContinuousReferenceSubnetwork ref;
        math::ContinuousReversibleSubnetwork sys(20);

        for (auto i : range(n)) {
            sys.augment(p(i), -R(i, i), R);
            ref.augment(p(i), -R(i, i), R);
            
            uint a = random_range(0, i+1), b = random_range(0, i+1);
            real c = random_float();

            ct(HERE).all(ct.within(1e-8), sys.fundamental_matrix(), ref.fundamental_matrix());

            ct(HERE).all(ct.within(1e-8), sys.escape_probabilities(a), ref.escape_probabilities(a));
            ct(HERE).all(ct.within(1e-8), sys.cut_time_losses(a), ref.cut_time_losses(a));
            ct(HERE).within(sys.sample_time(a, c), ref.sample_time(a, c), 1e-8);
            real T = ref.sample_time(a, c);
            ct(HERE).all(ct.within(1e-8), sys.sample_escape_probabilities(a, T), ref.sample_escape_probabilities(a, T), "sample_escape_probabilities");
            ct(HERE).all(ct.within(1e-8), sys.conditional_occupation_times(a, b), ref.conditional_occupation_times(a, b), "conditional_occupation_times");
            ct(HERE).within(sys.conditional_sample_time(a, b, c), ref.conditional_sample_time(a, b, c), 1e-8, "conditional_sample_time");
            ct(HERE).all(ct.within(1e-8), sys.sample_occupation_times(a, b, T), ref.sample_occupation_times(a, b, T), "sample_occupation_times");

            ct(HERE).all(ct.within(1e-8), sys.escape_probabilities_before(a, b), ref.escape_probabilities_before(a, b), "escape_probabilities_before");
        }
    });
};

