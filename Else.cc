RELEASE_TEST("math/exponential-fit") = [](Context ct) {
    uint n = 10;
    Mat<real> L = la::randu(n, n);
    L = L + L.t();
    L = la::diagmat(la::randu(n) + la::sum(L).t()) - L;

    Col<real> d(n, la::fill::zeros); d(0) = 1;
    Col<real> o(n, la::fill::ones);
    Col<real> v;
    Mat<real> V;
    la::eig_sym(v, V, L);

    for (auto i : range(100000)) {
        real c = random_float();
        Col<real> a = (V.t() * d) % (V.t() * o);
        real t = exponential_fit(a, Col<real>(-v), c);
        ct(HERE).within(c, la::dot(a, la::exp(-v * t)), 1e-7);
    }
};

